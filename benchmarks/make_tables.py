#!/usr/bin/env python3
"""
Generate the thesis section-7 LaTeX tables + verdict-stability summary from
the single consolidated results.csv (partitioned by the `group` column).

Outputs (under benchmarks/tables/ and benchmarks/):
  tables/regime_table.tex   regimes A-F x grid-protocols (verdict, WCRT, #execs, prune, [elected,no-leader])
  tables/heatmap_3pc.tex    3PC pruning gradient, L/U x W/U matrix (sd/U=0)
  tables/native_summary.tex raft native-axis summary rows
  VERDICT_STABILITY.md      anti-cherry-picking prose summary (deliverable 3)
"""
import csv, os, collections

HERE = os.path.dirname(os.path.abspath(__file__))
TABLES = os.path.join(HERE, "tables")

def load():
    # single consolidated results file (utf-8-sig tolerates a spreadsheet BOM)
    p = os.path.join(HERE, "results.csv")
    return list(csv.DictReader(open(p, encoding="utf-8-sig"))) if os.path.exists(p) else []

ROWS = load()

def cell(proto, lr, sr, wr, N="3"):
    """Look up one grid cell. lr/sr float, wr int."""
    for x in ROWS:
        if (x["protocol"] == proto and x["N"] == str(N)
                and x["l_over_u"] == str(lr) and x["sd_over_u"] == str(sr)
                and x["w_over_u"] == str(wr)):
            return x
    return None

# ---- regime A-F snapping to the grid (author choices; see README footnote) --
# Each regime's (L/U, sd/U, W/U) midpoint snapped to the nearest grid value;
# ties broken to the lower grid value. F's true sd/U >> 1 is outside the grid
# (capped at the grid max 0.5).  (lr, sr, wr)
REGIMES = [
    ("A", "Intra-DC RDMA (tight)",        0.0,  0.0, 10),
    ("B", "Intra-DC / intra-AZ TCP",      0.25, 0.5, 10),
    ("C", "Inter-AZ (same region)",       0.0,  0.25, 10),
    ("D", "Inter-region (regional pair)", 0.0,  0.0, 10),
    ("E", "Inter-region (transcont.)",    0.25, 0.0, 7),
    ("F", "Adversarial / congested",      0.0,  0.5, 2),
]

# (protocol, label, outcome) where outcome = "le" (elected/no-leader) | "commit" (commit/abort)
GRID_PROTOS = [
    ("three_pc_timed",                    "3PC (correct)",          "commit"),
    ("three_pc_timed_buggy",              "3PC (buggy)",            "commit"),
    ("comm_closed_leader_election",       "Comm-closed LE",         "le"),
    ("comm_closed_leader_election_inbox", "Comm-closed LE (inbox)", "le"),
]

def tex_escape(s): return s.replace("&", r"\&").replace("_", r"\_")
def _fnum(s):
    try: return float(s)
    except (ValueError, TypeError): return None
def fmt2(s):
    if s in ("", None): return "---"
    v = _fnum(s)
    return f"{v:.2f}" if v is not None else tex_escape(str(s))

# --------------------------------------------------------------------------- #
def make_regime_table():
    out = []
    out.append(r"% Auto-generated by make_tables.py -- do not edit by hand.")
    out.append(r"% Per-regime cells: each regime A-F snapped to the nearest grid point")
    out.append(r"% (U=20 ticks; L/U in {0,.25,.5,.9}, W/U in {2,3,5,7,10}, sd/U in {0,.25,.5}).")
    out.append(r"% WCRT column is 'needs instr.' everywhere: max tau_hi is not exposed by Stats")
    out.append(r"% on this branch (deferred to a separate verified instrumentation pass).")
    for proto, label, outcome in GRID_PROTOS:
        ncol = "lllrrrrr"  # all variants carry one trailing outcome column
        out_hdr = "elected / no-leader" if outcome == "le" else "commit / abort"
        out.append(r"\begin{table}[t]\centering")
        out.append(r"\caption{%s: MUST-$\tau$ vs untimed MUST across the cited network regimes (A--F), $N=3$, $U=20$.}" % tex_escape(label))
        out.append(r"\begin{tabular}{%s}" % ncol)
        out.append(r"\toprule")
        out.append(r"Regime & (L/U, sd/U, W/U) & Verdict & WCRT & base \#execs & timed \#execs & prune$\times$ & %s \\" % out_hdr)
        out.append(r"\midrule")
        for tag, name, lr, sr, wr in REGIMES:
            x = cell(proto, lr, sr, wr)
            trip = "(%.2g, %.2g, %d)" % (lr, sr, wr)
            if x is None:
                out.append(r"%s %s & %s & --- & --- & --- & --- & --- \\" % (tag, "", trip)); continue
            # buggy: both runs fire, so show base/timed verdicts together
            if proto == "three_pc_timed_buggy":
                bv = {"hold": r"\textsf{h}", "FIRE": r"\textbf{F}"}.get(x.get("baseline_verdict",""), tex_escape(x.get("baseline_verdict","?")))
                tv = {"hold": r"\textsf{h}", "FIRE": r"\textbf{F}"}.get(x["verdict"], tex_escape(x["verdict"]))
                verdict = r"base=%s/timed=%s" % (bv, tv)
            else:
                verdict = {"hold": r"\textsf{hold}", "FIRE": r"\textbf{FIRE}"}.get(x["verdict"], tex_escape(x["verdict"]))
            execs = x["execs"] if x["execs"] != "" else "---"
            bexecs = x.get("baseline_execs", "") or "---"
            prune = fmt2(x["pruning_x"]) if x["pruning_x"] not in ("", None) else "---"
            if outcome == "le":
                outcol = r"%s / %s" % (x["leaders_elected_total"], x["no_leader_execs"])
            else:
                outcol = r"%s / %s" % (x.get("commit_execs", "—"), x.get("abort_execs", "—"))
            out.append(r"%s. %s & %s & %s & n/a & %s & %s & %s & %s \\"
                       % (tag, tex_escape(name), trip, verdict, bexecs, execs, prune, outcol))
        out.append(r"\bottomrule")
        out.append(r"\end{tabular}")
        out.append(r"\end{table}")
        out.append("")
    open(os.path.join(TABLES, "regime_table.tex"), "w").write("\n".join(out))
    print("wrote tables/regime_table.tex")

def make_heatmap_3pc():
    W = [2, 3, 5, 7, 10]; L = [0.0, 0.25, 0.5, 0.9]
    out = [r"% 3PC (correct) pruning gradient: timed prunes more as L/U tightens. sd/U=0, N=3, U=20.",
           r"\begin{table}[t]\centering",
           r"\caption{3PC (correct): pruning ratio (baseline/timed \#execs) over the $L/U\times W/U$ grid, $sd/U=0$.}",
           r"\begin{tabular}{l" + "r"*len(W) + "}", r"\toprule",
           r"$L/U \backslash\ W/U$ & " + " & ".join(str(w) for w in W) + r" \\", r"\midrule"]
    for l in L:
        cells = []
        for w in W:
            x = cell("three_pc_timed", l, 0.0, w)
            cells.append(fmt2(x["pruning_x"]) if x else "---")
        out.append("%.2g & " % l + " & ".join(cells) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    # second matrix: timed #execs (the literal state-space size that is pruned)
    out += [r"\begin{table}[t]\centering",
            r"\caption{3PC (correct): timed \#execs over the $L/U\times W/U$ grid, $sd/U=0$, $N=3$ (lower = more pruning).}",
            r"\begin{tabular}{l" + "r"*len(W) + "}", r"\toprule",
            r"$L/U \backslash\ W/U$ & " + " & ".join(str(w) for w in W) + r" \\", r"\midrule"]
    for l in L:
        cells = []
        for w in W:
            x = cell("three_pc_timed", l, 0.0, w)
            cells.append(x["execs"] if x else "---")
        out.append("%.2g & " % l + " & ".join(cells) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    open(os.path.join(TABLES, "heatmap_3pc.tex"), "w").write("\n".join(out))
    print("wrote tables/heatmap_3pc.tex")

def make_native_summary():
    out = [r"% raft native-axis summary (the section-7 W/U/L/sd grid does not apply:",
           r"% raft uses U=1, sd=(N-1)*delta, no recv-timeout W).",
           r"\begin{table}[t]\centering",
           r"\caption{Raft (native-axis protocol; no $W/U$ grid).}",
           r"\begin{tabular}{llrrrrll}", r"\toprule",
           r"Protocol & params & base \#execs & timed \#execs & block & prune$\times$ & verdict & outcome (timed) \\", r"\midrule"]
    for x in ROWS:
        if x["protocol"] == "raft_leader_election" and x["status"] == "ok":
            out.append(r"Raft LE & $N{=}%s,\delta{=}%s,R{=}%s$ & %s & %s & %s & %s & \textsf{%s} & elected/no-leader %s/%s \\" %
                       (x["N"], x["delta"], x["rounds"], x.get("baseline_execs","") or "---", x["execs"], x["block"],
                        fmt2(x["pruning_x"]), x["verdict"], x["leaders_elected_total"], x["no_leader_execs"]))
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    open(os.path.join(TABLES, "native_summary.tex"), "w").write("\n".join(out))
    print("wrote tables/native_summary.tex")

def make_stability():
    L = [0.0, 0.25, 0.5, 0.9]; W = [2, 3, 5, 7, 10]; SD = [0.0, 0.25, 0.5]
    def proto_rows(p, N="3"): return [x for x in ROWS if x["protocol"] == p and (N is None or x["N"] == str(N))]
    def prunes(rows): return [v for v in (_fnum(x["pruning_x"]) for x in rows) if v is not None]
    out = ["# Verdict-stability summary (anti-cherry-picking defence)", "",
           "Every number below is a TraceForge run on the `inbox` branch (U=20 ticks). "
           "WCRT (axis 3, max tau_hi) is not exposed by `Stats` on this branch and is "
           "deferred to a separate verified instrumentation pass; it is marked n/a everywhere.", ""]

    # 3PC correct
    c = proto_rows("three_pc_timed")
    holds = sum(1 for x in c if x["verdict"] == "hold")
    pr = prunes(c)
    out.append(f"## 3PC (correct) -- the pruning template")
    out.append(f"- Safety (atomicity) **HOLDS in all {len(c)}/{len(c)} grid cells** (robust; no violating corner).")
    # commit/abort outcome (analog of the LE election count)
    def _ints(rows, k): return [int(x[k]) for x in rows if str(x.get(k, "")).lstrip("-").isdigit()]
    tc, ta = _ints(c, "commit_execs"), _ints(c, "abort_execs")
    bc = _ints(c, "baseline_commit_execs")
    if tc:
        out.append(f"- **Commit-outcome axis (commit/abort, the commit-protocol analog of elected/no-leader):** "
                   f"across the {len(c)} N=3 cells the **timed model reaches a COMMIT in {sum(tc)} executions total "
                   f"(every cell = 0)** -- every completed timed execution aborts ({min(ta)}-{max(ta)} per cell) or stalls "
                   f"at the ack phase; meanwhile the untimed baseline commits {bc[0] if bc else '?'} per cell. "
                   f"**FLAG:** timed 3PC never committing is a strong result that needs interpretation -- it is consistent "
                   f"across all W/U (incl. loose W/U=10) and N, which points to the ack-phase `sleep(delta=W+1)` making "
                   f"Acks time out in the timed model. Treat as either a genuine timed-liveness finding (3PC cannot make "
                   f"progress to commit under these timing assumptions) OR an artifact of the example's ack-phase timing "
                   f"to be reviewed before publishing. (commit+abort <= execs; the remainder are ack-stalls.)")
    out.append(f"- Pruning ratio ranges **{min(pr):.2f}x .. {max(pr):.2f}x** (N=3); it *increases* as transit tightens "
               f"(L/U 0->0.9) and saturates past W/U=3. The timed model removes orderings the untimed checker must explore.")
    c4 = [x for x in ROWS if x["protocol"] == "three_pc_timed" and x["N"] == "4"]
    if c4:
        pr4 = prunes(c4)
        h4 = sum(1 for x in c4 if x["verdict"] == "hold")
        out.append(f"- **N-scaling:** at N=4 (60-cell grid, tail) safety still HOLDS in all {h4}/{len(c4)} cells and pruning "
                   f"jumps to **{min(pr4):.1f}x .. {max(pr4):.1f}x** -- the timed model's advantage grows with N.")
    out.append("")

    # 3PC buggy
    b = proto_rows("three_pc_timed_buggy")
    fires = sum(1 for x in b if x["verdict"] == "FIRE")
    bfires = sum(1 for x in b if x.get("baseline_verdict") == "FIRE")
    out.append(f"## 3PC (buggy) -- the safety-bug witness")
    out.append(f"- The injected majority-commit bug **FIRES in all {fires}/{len(b)} cells under MUST-tau (timed)** AND in "
               f"all {bfires}/{len(b)} cells under untimed MUST (baseline) -- L and sd are now correctly threaded into the "
               f"timed run (the L/U axis varies 0..0.9, sd/U 0..0.5, W/U 2..10).")
    out.append(f"- **Honest finding:** this bug is NOT timing-gated within the section-7 grid -- it is a pure logic error "
               f"(a No-voter can receive Commit whenever the coordinator sees a majority of Yes), so **both** the timed and "
               f"the untimed checker find it in every regime. It is a safety bug the timed model reliably catches, but NOT "
               f"an example of a 'timing-only' bug that an untimed checker would miss. (No fire-vs-hold variation across the "
               f"grid; verify the corrected L/sd threading in `results.csv`.)")
    out.append("")

    # comm-closed (both)
    for p, name in [("comm_closed_leader_election", "Comm-closed LE"),
                    ("comm_closed_leader_election_inbox", "Comm-closed LE (inbox)")]:
        c = proto_rows(p)
        holds = sum(1 for x in c if x["verdict"] == "hold")
        pr = prunes(c)
        # election degradation across L/U at sd=0,W/U=5
        el = []
        for l in L:
            x = cell(p, l, 0.0, 5)
            if x: el.append((l, x["leaders_elected_total"], x["no_leader_execs"]))
        out.append(f"## {name}")
        out.append(f"- Agreement (<=1 leader/ballot) **HOLDS in all {holds}/{len(c)} cells** (robust).")
        out.append(f"- Pruning is ~1.00x for L/U in {{0,0.25,0.5}} and only **{max(pr):.2f}x at L/U=0.9**: the timed "
                   f"model prunes only in the extreme-tight-transit corner. **W/U has no effect** in the section-7 "
                   f"range (W>=40 >> U=20, so the recv timeout never bites).")
        out.append(f"- **sd/U has no effect AT BALLOTS=1** (all these runs use --ballots 1). This is EXPECTED, not a "
                   f"general result: sd is message storage-lifetime, which can only bite across a *ballot boundary*, and "
                   f"a single ballot has none. Whether sd becomes load-bearing at ballots>=2 is a separate question; "
                   f"ballots=2 is itself a state-space blowup (does not finish at N=3 in 120s) -- see the `group=ballots2` "
                   f"rows in results.csv for the bounded sd=0-vs-sd=0.5 test.")
        out.append("- Successful-election count vs transit tightness (sd/U=0, W/U=5): " +
                   ", ".join(f"L/U={l}: {e} elected / {nl} no-leader" for l, e, nl in el) + ".")
        out.append(f"  Tightening transit to L/U=0.9 *reduces* successful elections (the only timing axis that bites here).")
        out.append("")

    # comm-closed inbox: larger-N coverage (tight corner only; baseline intractable)
    inb = [x for x in ROWS if x["protocol"] == "comm_closed_leader_election_inbox" and x["N"] in ("4", "5")]
    if inb:
        out.append("## Comm-closed LE (inbox) -- larger-N coverage")
        out.append("The inbox variant completes exhaustive TIMED verification at N=5 (1 ballot) in about 48 min. "
                   "IMPORTANT: this does not by itself prove the inbox variant scales better than the others. The "
                   "non-inbox N=5 and raft N=5 runs were only given a 600 s cap and timed out; they were not retried "
                   "with a longer cap, so they are undertested, not shown intractable. A fair comparison needs equal "
                   "time budgets. Timed-only, tight corner (L/U=0.9, W/U=2, sd/U=0); the untimed baseline did not "
                   "finish in 9.3 h, so pruning is n/a.")
        for x in sorted(inb, key=lambda z: (z["N"], z["rounds"])):
            if x["status"] == "ok":
                ex, el, nl = int(x["execs"]), int(x["leaders_elected_total"]), int(x["no_leader_execs"])
                out.append(f"- **N={x['N']}, ballots={x['rounds']}: COMPLETES** in {float(x['wall_time'])/60:.0f} min -- "
                           f"{ex:,} execs, **{el:,} elected ({el/ex*100:.0f}%) / {nl:,} no-leader ({nl/ex*100:.0f}%)**, "
                           f"safety holds. The no-leader fraction is large -- at N=5 tight transit most schedules split-vote.")
            else:
                waited_h = float(x['wall_time'])/3600 if str(x.get('wall_time','')).replace('.','',1).isdigit() else 0
                out.append(f"- N={x['N']}, ballots={x['rounds']}: **{x['status']}** -- waited ~{waited_h:.1f} h and it "
                           f"**did not finish; the result is unknown** (the {x['rounds']}-ballot space is far larger; "
                           f"exhaustive timed verification did not complete).")
        out.append("")

    # raft
    r = proto_rows("raft_leader_election")
    out.append("## Raft leader election")
    out.append(f"- Election-Safety (<=1 leader/term) **HOLDS in all {len(r)}/{len(r)} cells**.")
    if r:
        ex = r[0]["execs"]; bl = r[0]["block"]
        out.append(f"- At N=3 the result is **invariant to (delta in {{1,2,3}}, rounds in {{1,2}})**: every cell gives "
                   f"timed execs={ex}, block={bl}. The election always resolves in round 1, and delta only changes "
                   f"sleep magnitudes, not the timed exec count.")
        out.append(f"- Leader-election outcome (structural, from Stats): **leaders_elected_total = execs = {ex}**, "
                   f"**no_leader_execs = block = {bl}**. Justification: a complete raft execution provably elects exactly "
                   f"one leader (two-per-term fires the Election-Safety assert, which holds; zero-leader is impossible "
                   f"because a never-winning Candidate blocks on recv and is counted as `block`, not a complete exec). "
                   f"So ~{int(bl)/(int(ex)+int(bl))*100:.0f}% of explored schedules are split-vote / no-leader stalls.")
    out.append("")

    # ballots=2 sd test (comm-closed N=3 rounds=2 in the consolidated file)
    b2 = [x for x in ROWS if x["protocol"].startswith("comm_closed")
          and x["N"] == "3" and str(x.get("rounds", "")) == "2"]
    if b2:
        def b2cell(l, s):
            for x in b2:
                if x["l_over_u"] == str(l) and x["sd_over_u"] == str(s): return x
            return None
        out.append("## Comm-closed LE at ballots=2 -- does `sd` finally bite? (YES)")
        out.append("The single-ballot grid showed sd inert; that is an artifact of B=1 (no ballot boundary). "
                   "At **B=2** (N=3, timed-only; the untimed baseline is intractable here), sd becomes load-bearing:")
        for l in (0.0, 0.9):
            c0, c5 = b2cell(l, 0.0), b2cell(l, 0.5)
            if c0 and c5:
                e0, e5 = int(c0["execs"]), int(c5["execs"])
                el0, el5 = int(c0["leaders_elected_total"]), int(c5["leaders_elected_total"])
                tag = "loose transit (L/U=0)" if l == 0.0 else "tight transit (L/U=0.9)"
                out.append(f"- {tag}: sd/U=0 -> {e0:,} execs / {el0:,} elected;  sd/U=0.5 -> {e5:,} execs / {el5:,} elected "
                           f"(execs x{e5/e0:.2f}, elected x{el5/el0:.2f}).")
        out.append("- So `sd` has a small effect at loose transit but a LARGE one at tight transit (state space and "
                   "successful elections ~double at sd/U=0.5). This confirms the network-parameters report's inclusion of "
                   "the sd axis: it matters precisely when storage must outlive a ballot boundary. "
                   "**Ballots was fixed at 1 for the main grid** (a structural axis, not a network ratio, and B=2 is a "
                   "~5000x state-space blowup: the B=1 cell with 10,232 execs becomes ~52,000,000 at B=2).")
        out.append("- **Untimed (baseline) B=2 was NOT run to completion** (skipped per time budget). "
                   "ROUGH ESTIMATE ONLY (not measured, treat as inaccurate): the untimed run reached 2,000,000 execs at "
                   "~4,500 execs/s before being aborted; since untimed >= timed it is >=52M execs, so completion would take "
                   "**~3-4 hours at full CPU** (a lower-bound projection from the early-run rate, which may decline; the true "
                   "untimed exec count is unknown). Hence `baseline=not-run` and `pruning_x=n/a` for the B=2 rows.")
        out.append("")

    open(os.path.join(HERE, "VERDICT_STABILITY.md"), "w").write("\n".join(out))
    print("wrote VERDICT_STABILITY.md")

if __name__ == "__main__":
    os.makedirs(TABLES, exist_ok=True)
    print(f"loaded {len(ROWS)} rows")
    make_regime_table()
    make_heatmap_3pc()
    make_native_summary()
    make_stability()
